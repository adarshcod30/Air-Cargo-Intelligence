@app.get("/api/v1/airports/rankings", response_model=QueryResponse, tags=["airports"])
def airport_rankings(
    period: str | None = Query(None, description="e.g. 2026-07"),
    direction: str = Query("TOTAL", pattern="^(INTERNATIONAL|DOMESTIC|TOTAL)$"),
    country: str | None = None,
    order_by: str = Query("tonnage_mt", pattern="^(tonnage_mt|growth_yoy_pct)$"),
    min_tonnage_mt: float | None = Query(
        None,
        description="Minimum tonnage to qualify. Defaults to 100 MT when "
                    "ordering by growth, because a 4-tonne airport posting "
                    "486% is noise rather than news.",
    ),
    limit: int = Query(20, ge=1, le=200),
    session: Session = Depends(get_session),
) -> QueryResponse:
    """Airports ranked by tonnage or by year-on-year growth.

    A ranking is always scoped to one period. Without that the endpoint
    summed across every period held, so Eurostat's annual figure for
    Frankfurt (3.8m MT for a year) outranked Delhi's monthly one
    (105k MT for a month) - a league table that looks authoritative and
    compares a year against a month.
    """
    if period is None:
        period = _latest_period(session, "AIRPORT")
    filters: dict = {"grain": "AIRPORT", "direction": direction, "period": period}
    floor = min_tonnage_mt if min_tonnage_mt is not None else (
        100.0 if order_by == "growth_yoy_pct" else None
    )
    if floor:
        filters["min_tonnage_kg"] = floor * 1000.0
    if country:
        filters["country"] = country
    return _execute(session, QuerySpec(
        metrics=["tonnage_mt", "growth_yoy_pct", "source_count"],
        dimensions=["airport_iata", "airport_name", "country"],
        filters=filters, order_by=order_by, limit=limit,
    ))


@app.get("/api/v1/airports/trend", response_model=QueryResponse, tags=["airports"])
def airport_trend(
    iata: str = Query(min_length=3, max_length=3),
    direction: str = Query("TOTAL", pattern="^(INTERNATIONAL|DOMESTIC|TOTAL)$"),
    session: Session = Depends(get_session),
) -> QueryResponse:
    """One airport's series over every period held."""
    return _execute(session, QuerySpec(
        metrics=["tonnage_mt", "growth_yoy_pct"],
        dimensions=["period", "airport_iata"],
        filters={"grain": "AIRPORT", "direction": direction,
                 "airport_iata": iata.upper()},
        order_by="period", descending=False, limit=200,
    ))


# ------------------------------------------------------------- airlines --

@app.get("/api/v1/airlines/share", response_model=QueryResponse, tags=["airlines"])
def airline_share(
    direction: str = Query("TOTAL", pattern="^(INTERNATIONAL|DOMESTIC|TOTAL)$"),
    include_aggregates: bool = Query(
        False,
        description="Industry totals such as 'All Scheduled Indian Airlines'. "
                    "Off by default: summing them beside carriers double-counts.",
    ),
    limit: int = Query(20, ge=1, le=200),
    session: Session = Depends(get_session),
) -> QueryResponse:
    filters: dict = {"grain": "AIRLINE", "direction": direction}
    if not include_aggregates:
        filters["exclude_aggregate_airlines"] = True
    return _execute(session, QuerySpec(
        metrics=["tonnage_mt", "record_count"],
        dimensions=["airline_name"],
        filters=filters, order_by="tonnage_mt", limit=limit,
    ))


