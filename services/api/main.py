"""HTTP serving layer.

Every endpoint compiles through the semantic layer rather than writing
its own SQL, so a metric has one definition and the dashboard and the
chat interface cannot drift apart. Endpoints are thin on purpose: they
translate URL parameters into a QuerySpec and hand back what comes out,
with its citations.
"""

from __future__ import annotations

from pathlib import Path

from fastapi import Depends, FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from sqlalchemy import text
from sqlalchemy.orm import Session

from services.api.deps import get_session
from services.api.schemas import (
    ChatRequest,
    ChatResponse,
    HealthResponse,
    QueryResponse,
)
from services.common.logging import get_logger
from services.semantic import registry
from services.semantic.compiler import QueryRejected, QuerySpec
from services.semantic.executor import run

log = get_logger(__name__)

app = FastAPI(
    title="Air Cargo Intelligence API",
    version="0.1.0",
    description=(
        "Every figure returned by this API is computed by SQL over a governed "
        "semantic layer and carries the source document behind it. No number "
        "is generated by a language model."
    ),
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:3000", "http://127.0.0.1:3000"],
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


# The dashboard is served by the API rather than from a separate dev
# server: it is the same origin, so there is no CORS dance, and there is
# nothing to build before it will run.
WEB_DIR = Path(__file__).resolve().parents[2] / "web"
if WEB_DIR.is_dir():
    app.mount("/static", StaticFiles(directory=WEB_DIR), name="static")

    @app.get("/", include_in_schema=False)
    def dashboard() -> FileResponse:
        return FileResponse(WEB_DIR / "index.html")


def _latest_period(session: Session, grain: str) -> str:
    """The most recent period held at this grain."""
    row = session.execute(
        text("SELECT period FROM v_cargo_fact WHERE grain = :g "
             "ORDER BY sort_key DESC LIMIT 1"),
        {"g": grain},
    ).first()
    return row[0] if row else "unknown"


def _execute(session: Session, spec: QuerySpec) -> QueryResponse:
    try:
        result = run(session, spec)
    except QueryRejected as exc:
        # A rejected query is a client error, and the message names what
        # was not recognised rather than leaking the SQL that was almost
        # built.
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return QueryResponse(**result.to_dict())


# --------------------------------------------------------------- health --

@app.get("/api/v1/health", response_model=HealthResponse, tags=["meta"])
def health(session: Session = Depends(get_session)) -> HealthResponse:
    counts = session.execute(text("""
        SELECT
          (SELECT count(*) FROM fact_cargo_movement),
          (SELECT count(*) FROM dim_airport),
          (SELECT count(*) FROM dim_airline),
          (SELECT count(*) FROM dim_period)
    """)).one()
    return HealthResponse(
        status="ok", database="connected",
        facts=counts[0], airports=counts[1], airlines=counts[2], periods=counts[3],
    )


@app.get("/api/v1/semantic", tags=["meta"])
def semantic_layer() -> dict:
    """The metric registry, so a client can discover what it may ask for."""
    return registry.describe()


