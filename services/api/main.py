@app.get("/api/v1/anomalies", tags=["intelligence"])
def anomalies(
    severity: str | None = Query(None, pattern="^(LOW|MEDIUM|HIGH)$"),
    grain: str | None = Query(None, pattern="^(AIRPORT|AIRLINE)$"),
    limit: int = Query(50, ge=1, le=200),
    session: Session = Depends(get_session),
) -> dict:
    """Detected anomalies, most deviant first."""
    rows = session.execute(text("""
        SELECT entity_key, COALESCE(airport_name, airline_name) AS entity_name,
               grain, direction, period,
               ROUND((observed_kg/1000)::numeric, 1) AS observed_mt,
               ROUND((expected_kg/1000)::numeric, 1) AS expected_mt,
               deviation_pct, z_score, method, severity
        FROM v_anomaly
        WHERE (CAST(:severity AS text) IS NULL OR severity = CAST(:severity AS text))
          AND (CAST(:grain AS text) IS NULL OR grain = CAST(:grain AS text))
        ORDER BY abs(deviation_pct) DESC NULLS LAST
        LIMIT :limit
    """), {"severity": severity, "grain": grain, "limit": limit}).mappings().all()
    return {"rows": [dict(r) for r in rows], "row_count": len(rows)}


@app.get("/api/v1/forecasts", tags=["intelligence"])
def forecasts(
    grain: str | None = Query(None, pattern="^(AIRPORT|AIRLINE)$"),
    horizon: int | None = Query(None, ge=1, le=12),
    limit: int = Query(50, ge=1, le=200),
    session: Session = Depends(get_session),
) -> dict:
    """Forecasts, each with its interval and the backtest error behind it."""
    rows = session.execute(text("""
        SELECT entity_key, COALESCE(airport_name, airline_name) AS entity_name,
               grain, direction, period, horizon,
               ROUND((predicted_kg/1000)::numeric, 1) AS predicted_mt,
               ROUND((lower_kg/1000)::numeric, 1)     AS lower_mt,
               ROUND((upper_kg/1000)::numeric, 1)     AS upper_mt,
               model, ROUND(backtest_mape::numeric, 1) AS backtest_mape_pct
        FROM v_forecast
        WHERE (CAST(:grain AS text) IS NULL OR grain = CAST(:grain AS text))
          AND (CAST(:horizon AS int) IS NULL OR horizon = CAST(:horizon AS int))
        ORDER BY predicted_kg DESC
        LIMIT :limit
    """), {"grain": grain, "horizon": horizon, "limit": limit}).mappings().all()
    return {"rows": [dict(r) for r in rows], "row_count": len(rows)}


# --------------------------------------------------------------- sources --

@app.get("/api/v1/sources", tags=["meta"])
def sources(session: Session = Depends(get_session)) -> dict:
    """Every ingested document and how many facts rest on it."""
    rows = session.execute(text("""
        SELECT publisher, count(*) AS documents, sum(fact_count) AS facts,
               max(retrieved_at) AS last_retrieved
        FROM v_source GROUP BY publisher ORDER BY facts DESC NULLS LAST
    """)).mappings().all()
    return {"publishers": [dict(r) for r in rows]}


# ------------------------------------------------------------------ chat --

@app.post("/api/v1/chat/query", response_model=ChatResponse, tags=["chat"])
def chat_query(
    request: ChatRequest, session: Session = Depends(get_session)
) -> ChatResponse:
    """Answer a natural-language question, grounded in stored rows.

    The question is classified and mapped onto registered metrics; it
    never becomes free-form SQL. `understood_as` is returned so a
    misreading is visible to the user rather than hidden behind a
    confident sentence.
    """
    from services.semantic.nl import answer

    try:
        result = answer(session, request.question)
    except QueryRejected as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return ChatResponse(**result)
